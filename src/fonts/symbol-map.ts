export type SymbolFontKind = 'symbol' | 'wingdings' | 'wingdings2' | 'wingdings3' | 'webdings';

export function symbolFontKind(family: string): SymbolFontKind | null {
  const f = family.toLowerCase().replace(/\s+/g, ' ').trim();
  if (f === 'symbol' || f === 'symbol mt') return 'symbol';
  if (f === 'wingdings' || f === 'wingdings 1') return 'wingdings';
  if (f === 'wingdings 2') return 'wingdings2';
  if (f === 'wingdings 3') return 'wingdings3';
  if (f === 'webdings') return 'webdings';
  return null;
}

/** Map a character in a symbol font (0x20..0xFF or the U+F020..U+F0FF private range) to Unicode. */
export function mapSymbolChar(kind: SymbolFontKind, cp: number): number {
  const code = cp >= 0xf000 && cp <= 0xf0ff ? cp - 0xf000 : cp;
  if (code < 0x20 || code > 0xff) return cp;
  let mapped = 0;
  if (kind === 'symbol') mapped = SYMBOL[code - 0x20] ?? 0;
  else if (kind === 'wingdings') mapped = WINGDINGS[code - 0x20] ?? 0;
  else if (kind === 'wingdings2') mapped = WINGDINGS2[code] ?? 0;
  else if (kind === 'wingdings3') mapped = WINGDINGS3[code] ?? 0;
  else if (kind === 'webdings') mapped = code === 0x61 ? 0x2713 : code === 0x3d ? 0x25a0 : 0;
  if (mapped) return mapped;
  // Unknown dingbat: a bullet is a far better guess than a missing-glyph box.
  return cp >= 0xf000 ? 0x2022 : code;
}
